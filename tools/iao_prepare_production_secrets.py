"""Create a private, one-time production bootstrap environment file.

Secret values are never printed. The resulting file must remain outside Git.
"""
from __future__ import annotations

import argparse
import os
import secrets
import stat
import time
from pathlib import Path


def write_production_secrets(path: Path, *, now: int | None = None) -> Path:
    target = path.expanduser()
    if target.exists() or target.is_symlink():
        raise FileExistsError("PRODUCTION_ENV_ALREADY_EXISTS")
    target.parent.mkdir(parents=True, exist_ok=True, mode=0o700)
    try:
        os.chmod(target.parent, 0o700)
    except OSError:
        pass
    timestamp = int(time.time() if now is None else now)
    values = {
        "APP_ENV": "production",
        "HOST": "0.0.0.0",
        "PORT": "8080",
        "IAO_STATE_DIR": "/var/lib/iao",
        "IAO_IDENTITY_ROLLBACK_DIR": "/var/lib/iao/identity-trust",
        "IAO_CORPUS_DIR": "/app/knowledge",
        "IAO_TASK_WORKER_ENABLED": "true",
        "MODEL_ADAPTER": "disabled",
        "PUBLIC_BASE_URL": "CHANGE_ME_HTTPS_ORIGIN",
        "IAO_CORS_ORIGINS": "CHANGE_ME_EXACT_BROWSER_ORIGIN",
        "IAO_SESSION_SIGNING_KEY": secrets.token_urlsafe(64),
        "AUDIT_HMAC_KEY": secrets.token_urlsafe(64),
        "IAO_DEVICE_ENROLLMENT_CODE": secrets.token_urlsafe(48),
        "IAO_DEVICE_ENROLLMENT_ENABLED": "1",
        "IAO_OPERATOR_BOOTSTRAP_CODE": secrets.token_urlsafe(48),
        "IAO_OPERATOR_BOOTSTRAP_EXPIRES_AT": str(timestamp + 900),
    }
    body = (
        "# Generated by tools/iao_prepare_production_secrets.py\n"
        "# Replace PUBLIC_BASE_URL and IAO_CORS_ORIGINS before deployment.\n"
        "# After first enrollment, disable enrollment and remove both one-time codes.\n"
        + "".join(f"{key}={value}\n" for key, value in values.items())
    )
    flags = os.O_WRONLY | os.O_CREAT | os.O_EXCL
    if hasattr(os, "O_NOFOLLOW"):
        flags |= os.O_NOFOLLOW
    descriptor = os.open(target, flags, 0o600)
    try:
        with os.fdopen(descriptor, "w", encoding="utf-8", newline="\n") as stream:
            stream.write(body)
            stream.flush()
            os.fsync(stream.fileno())
        os.chmod(target, stat.S_IRUSR | stat.S_IWUSR)
    except BaseException:
        try:
            target.unlink()
        except OSError:
            pass
        raise
    return target


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--output", type=Path, default=Path(".env.production"),
        help="private output path (must not already exist)",
    )
    args = parser.parse_args()
    try:
        target = write_production_secrets(args.output)
    except FileExistsError:
        parser.error("target already exists; refusing to overwrite production secrets")
    except OSError:
        parser.error("could not create private production environment file")
    print(f"Created private production environment file: {target}")
    print("Permissions: 0600. Secret values were not displayed.")
    print("Before deployment: set HTTPS PUBLIC_BASE_URL and exact IAO_CORS_ORIGINS.")
    print("After first device/root bootstrap: disable enrollment and remove one-time codes.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
